type Seed = Omit<Ad, "anatomy" | "designNotes"> & { extraNotes?: string[] };

function ad(seed: Seed): Ad {
  const { extraNotes, ...rest } = seed;
  return {
    ...rest,
    anatomy: ANATOMY[seed.format],
    designNotes: [...(extraNotes ?? []), ...NOTES[seed.format]],
  };
}

